export function normalizeLocale(rawLocale) {
  const value = String(rawLocale || "").trim().toLowerCase()
  if (value === "zh-cn" || value === "zh-hans" || value === "zh_cn") return "zh-CN"
  if (value === "zh-tw" || value === "zh-hant" || value === "zh-hk" || value === "zh_tw") {
    return "zh-TW"
  }
  return "en"
}

export function formatMessage(template, params) {
  const safeParams = params && typeof params === "object" ? params : {}
  return String(template).replace(/\{(\w+)\}/g, (_match, name) => {
    const val = safeParams[name]
    return val === undefined || val === null ? `{${name}}` : String(val)
  })
}

export function tForLocale(rawLocale, key, params) {
  const locale = normalizeLocale(rawLocale)
  const bundle = BUNDLES[locale] || BUNDLES.en
  const raw = bundle[key] !== undefined ? bundle[key] : BUNDLES.en[key]
  if (raw === undefined) return String(key)
  return formatMessage(raw, params)
}

export function useI18n() {
  const rawLocale = useLocale()
  const locale = computed(() => normalizeLocale(rawLocale.value))
  const t = (key, params) => tForLocale(locale.value, key, params)
  return { locale, t }
}

export function syncSettingsHostLabels(rawLocale, rootDoc) {
  const doc = rootDoc || (typeof document !== "undefined" ? document : null)
  if (!doc) return
  const title = tForLocale(rawLocale, "nav.settingsTitle")

  const navItems = doc.querySelectorAll(`[data-section="${SETTINGS_SECTION_ID}"]`)
  for (const navEl of navItems) {
    const labelSpan = navEl.querySelector("span.flex-1")
    if (labelSpan) {
      if (labelSpan.textContent !== title) labelSpan.textContent = title
      continue
    }
    const spans = navEl.querySelectorAll("span")
    if (spans.length >= 2) {
      const target = spans[1]
      if (target.textContent !== title) target.textContent = title
    }
  }

  const contributionHosts = doc.querySelectorAll(`[data-ext="${SETTINGS_SECTION_ID}"]`)
  for (const host of contributionHosts) {
    const sectionEl = typeof host.closest === "function" ? host.closest("section") : null
    const heading = sectionEl ? sectionEl.querySelector("header h2") : null
    if (heading && heading.textContent !== title) {
      heading.textContent = title
    }
  }
}
